"""Leakage-safe training entry point with MLflow tracking.

Key differences from the original exploratory notebook:
- SMOTE is inside the CV pipeline, never applied before RandomizedSearchCV.
- Imbalance strategies are compared using CV on training data only.
- The operating threshold is selected on a validation split, not the final test set.
- The final test set is touched once for unbiased reporting.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
import sklearn
import lightgbm
import imblearn
from imblearn.over_sampling import SMOTE
from imblearn.pipeline import Pipeline as ImbPipeline
from lightgbm import LGBMClassifier
from scipy.stats import randint, uniform
from sklearn.metrics import f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import RandomizedSearchCV, StratifiedKFold, train_test_split

RANDOM_STATE = 42
CAT_COLS = ["Gender", "Education_Level", "Marital_Status", "Income_Category", "Card_Category"]
DROP_COLS = ["CLIENTNUM", "Avg_Open_To_Buy"]
TARGET = "Attrition_Flag"
COST_FN = 20_000
COST_FP = 500


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_and_clean(path: Path) -> tuple[pd.DataFrame, pd.Series, pd.DataFrame]:
    df = pd.read_csv(path)

    # Some public copies include two helper columns generated by the dataset publisher.
    helper_cols = [c for c in df.columns if c.startswith("Naive_Bayes_Classifier")]
    if helper_cols:
        df = df.drop(columns=helper_cols)

    required = {TARGET, *CAT_COLS, *DROP_COLS}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"Dataset is missing required columns: {sorted(missing)}")

    df["Education_Level"] = df["Education_Level"].fillna("Unknown")
    df["Marital_Status"] = df["Marital_Status"].fillna("Unknown")
    df["Income_Category"] = df["Income_Category"].replace("abc", "Unknown").fillna("Unknown")

    raw_features = df.drop(columns=[TARGET, *DROP_COLS]).copy()

    model_df = df.drop(columns=DROP_COLS).copy()
    y = (model_df[TARGET] == "Attrited Customer").astype(int)
    X = pd.get_dummies(model_df.drop(columns=TARGET), columns=CAT_COLS, drop_first=True)
    return X, y, raw_features


def metric_dict(y_true: pd.Series, probabilities: np.ndarray, threshold: float = 0.5) -> dict[str, float]:
    pred = (probabilities >= threshold).astype(int)
    return {
        "recall": recall_score(y_true, pred),
        "precision": precision_score(y_true, pred, zero_division=0),
        "f1": f1_score(y_true, pred, zero_division=0),
        "roc_auc": roc_auc_score(y_true, probabilities),
    }


def choose_threshold(y_val: pd.Series, probabilities: np.ndarray) -> tuple[float, int]:
    thresholds = np.arange(0.01, 0.96, 0.01)
    costs: list[int] = []
    y_np = np.asarray(y_val)
    for threshold in thresholds:
        pred = (probabilities >= threshold).astype(int)
        fn = int(((y_np == 1) & (pred == 0)).sum())
        fp = int(((y_np == 0) & (pred == 1)).sum())
        costs.append(fn * COST_FN + fp * COST_FP)
    idx = int(np.argmin(costs))
    return float(thresholds[idx]), int(costs[idx])


def build_searches(neg_pos_ratio: float) -> dict[str, RandomizedSearchCV]:
    common_params = {
        "model__n_estimators": randint(100, 350),
        "model__num_leaves": randint(15, 64),
        "model__learning_rate": uniform(0.03, 0.17),
        "model__max_depth": randint(3, 10),
    }
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)

    strategies: dict[str, ImbPipeline] = {
        "smote": ImbPipeline(
            [
                ("smote", SMOTE(random_state=RANDOM_STATE)),
                ("model", LGBMClassifier(random_state=RANDOM_STATE, verbose=-1, n_jobs=1)),
            ]
        ),
        "class_weight": ImbPipeline(
            [
                ("model", LGBMClassifier(class_weight="balanced", random_state=RANDOM_STATE, verbose=-1, n_jobs=1)),
            ]
        ),
        "scale_pos_weight": ImbPipeline(
            [
                (
                    "model",
                    LGBMClassifier(
                        scale_pos_weight=neg_pos_ratio,
                        random_state=RANDOM_STATE,
                        verbose=-1,
                        n_jobs=1,
                    ),
                ),
            ]
        ),
    }

    return {
        name: RandomizedSearchCV(
            estimator=pipeline,
            param_distributions=common_params,
            n_iter=12,
            scoring="recall",
            cv=cv,
            random_state=RANDOM_STATE,
            n_jobs=-1,
            refit=True,
            return_train_score=False,
        )
        for name, pipeline in strategies.items()
    }


def refit_selected_model(
    strategy: str,
    search: RandomizedSearchCV,
    X: pd.DataFrame,
    y: pd.Series,
) -> ImbPipeline:
    params = search.best_params_
    if strategy == "smote":
        pipe = ImbPipeline(
            [
                ("smote", SMOTE(random_state=RANDOM_STATE)),
                ("model", LGBMClassifier(random_state=RANDOM_STATE, verbose=-1, n_jobs=1)),
            ]
        )
    elif strategy == "class_weight":
        pipe = ImbPipeline(
            [("model", LGBMClassifier(class_weight="balanced", random_state=RANDOM_STATE, verbose=-1, n_jobs=1))]
        )
    else:
        neg_pos_ratio = float((y == 0).sum() / (y == 1).sum())
        pipe = ImbPipeline(
            [
                (
                    "model",
                    LGBMClassifier(
                        scale_pos_weight=neg_pos_ratio,
                        random_state=RANDOM_STATE,
                        verbose=-1,
                        n_jobs=1,
                    ),
                )
            ]
        )
    pipe.set_params(**params)
    pipe.fit(X, y)
    return pipe


def build_reference_profile(raw_df: pd.DataFrame) -> dict[str, Any]:
    numeric_cols = raw_df.select_dtypes(include=[np.number]).columns.tolist()
    categorical_cols = [c for c in raw_df.columns if c not in numeric_cols]
    profile: dict[str, Any] = {"numeric": {}, "categorical": {}, "rows": int(len(raw_df))}

    for col in numeric_cols:
        series = raw_df[col].dropna().astype(float)
        quantiles = np.unique(series.quantile(np.linspace(0.1, 0.9, 9)).to_numpy())
        cuts = [float(v) for v in quantiles]
        edges = np.array([-np.inf, *cuts, np.inf])
        counts, _ = np.histogram(series, bins=edges)
        proportions = (counts / max(counts.sum(), 1)).tolist()
        profile["numeric"][col] = {"cuts": cuts, "proportions": proportions}

    for col in categorical_cols:
        proportions = raw_df[col].fillna("Unknown").astype(str).value_counts(normalize=True)
        profile["categorical"][col] = {str(k): float(v) for k, v in proportions.items()}
    return profile


def train(data_path: Path, output_dir: Path, enable_mlflow: bool = True) -> dict[str, Any]:
    X, y, raw_features = load_and_clean(data_path)

    X_train_val, X_test, y_train_val, y_test, raw_train_val, _ = train_test_split(
        X,
        y,
        raw_features,
        test_size=0.20,
        random_state=RANDOM_STATE,
        stratify=y,
    )
    X_train, X_val, y_train, y_val = train_test_split(
        X_train_val,
        y_train_val,
        test_size=0.20,
        random_state=RANDOM_STATE,
        stratify=y_train_val,
    )

    ratio = float((y_train == 0).sum() / (y_train == 1).sum())
    searches = build_searches(ratio)

    mlflow = None
    parent_run = None
    if enable_mlflow:
        try:
            import mlflow as _mlflow

            mlflow = _mlflow
            mlflow.set_experiment("credit-card-churn")
            parent_run = mlflow.start_run(run_name="p0-p1-training")
            mlflow.log_params(
                {
                    "dataset_sha256": sha256_file(data_path),
                    "rows": len(X),
                    "features_encoded": X.shape[1],
                    "random_state": RANDOM_STATE,
                    "threshold_cost_fn": COST_FN,
                    "threshold_cost_fp": COST_FP,
                }
            )
        except ImportError:
            print("MLflow is not installed; continuing without experiment tracking.")

    search_summary: dict[str, Any] = {}
    for name, search in searches.items():
        search.fit(X_train, y_train)
        val_proba = search.best_estimator_.predict_proba(X_val)[:, 1]
        val_metrics = metric_dict(y_val, val_proba)
        search_summary[name] = {
            "cv_recall": float(search.best_score_),
            "best_params": search.best_params_,
            "validation": val_metrics,
        }
        if mlflow:
            with mlflow.start_run(run_name=name, nested=True):
                mlflow.log_param("imbalance_strategy", name)
                mlflow.log_params({k.replace("model__", ""): v for k, v in search.best_params_.items()})
                mlflow.log_metric("cv_recall", float(search.best_score_))
                for metric, value in val_metrics.items():
                    mlflow.log_metric(f"val_{metric}", float(value))

    # Strategy/model choice is made using training-CV recall only; the test set remains untouched.
    selected_strategy = max(search_summary, key=lambda name: search_summary[name]["cv_recall"])
    selected_search = searches[selected_strategy]

    val_proba = selected_search.best_estimator_.predict_proba(X_val)[:, 1]
    threshold, validation_cost = choose_threshold(y_val, val_proba)

    final_pipeline = refit_selected_model(selected_strategy, selected_search, X_train_val, y_train_val)
    test_proba = final_pipeline.predict_proba(X_test)[:, 1]
    test_default = metric_dict(y_test, test_proba, threshold=0.5)
    test_operating = metric_dict(y_test, test_proba, threshold=threshold)

    # SMOTE is training-only, so persist only the fitted classifier for inference.
    model = final_pipeline.named_steps["model"]
    output_dir.mkdir(parents=True, exist_ok=True)
    artifact_path = output_dir / "model_artifacts.joblib"
    metadata = {
        "selected_strategy": selected_strategy,
        "best_cv_recall": search_summary[selected_strategy]["cv_recall"],
        "best_params": search_summary[selected_strategy]["best_params"],
        "validation_cost": validation_cost,
        "test_default_threshold_metrics": test_default,
        "test_operating_threshold_metrics": test_operating,
        "dataset_sha256": sha256_file(data_path),
        "random_state": RANDOM_STATE,
        "runtime_versions": {
            "scikit_learn": sklearn.__version__,
            "lightgbm": lightgbm.__version__,
            "imbalanced_learn": imblearn.__version__,
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "joblib": joblib.__version__,
        },
    }
    joblib.dump(
        {
            "model": model,
            "training_columns": X.columns.tolist(),
            "cat_cols": CAT_COLS,
            "raw_columns_expected": raw_features.columns.tolist(),
            "cost_optimal_threshold": threshold,
            "metadata": metadata,
        },
        artifact_path,
    )

    profile = build_reference_profile(raw_train_val)
    profile_path = output_dir / "reference_profile.json"
    profile_path.write_text(json.dumps(profile, indent=2), encoding="utf-8")

    report = {
        "selected_strategy": selected_strategy,
        "threshold": threshold,
        "validation_cost": validation_cost,
        "search_summary": search_summary,
        "test_default_threshold_metrics": test_default,
        "test_operating_threshold_metrics": test_operating,
        "artifact": str(artifact_path),
        "reference_profile": str(profile_path),
        "runtime_versions": metadata["runtime_versions"],
        "dataset_sha256": metadata["dataset_sha256"],
    }
    (output_dir / "training_report.json").write_text(json.dumps(report, indent=2, default=float), encoding="utf-8")

    if mlflow:
        mlflow.log_param("selected_strategy", selected_strategy)
        mlflow.log_param("operating_threshold", threshold)
        for metric, value in test_default.items():
            mlflow.log_metric(f"test_default_{metric}", float(value))
        for metric, value in test_operating.items():
            mlflow.log_metric(f"test_operating_{metric}", float(value))
        mlflow.log_artifact(str(artifact_path), artifact_path="model")
        mlflow.log_artifact(str(profile_path), artifact_path="monitoring")
        mlflow.log_artifact(str(output_dir / "training_report.json"), artifact_path="reports")
        if parent_run:
            mlflow.end_run()

    return report


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=Path("data/BankChurners.csv"))
    parser.add_argument("--output-dir", type=Path, default=Path("artifacts"))
    parser.add_argument("--no-mlflow", action="store_true")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    result = train(args.data, args.output_dir, enable_mlflow=not args.no_mlflow)
    print(json.dumps(result, indent=2, default=float))
